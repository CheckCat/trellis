#!/bin/sh
# Остановка локальной платформы Trellis (macOS / Linux).
#
# По умолчанию удаляются только контейнеры и сеть — том с данными
# ($DATA_VOLUME) остаётся, и следующий запуск поднимет платформу ровно с тем
# же прогрессом. Это не осторожность ради осторожности: прогресс ученика
# живёт ТОЛЬКО в этом томе, копии его нигде нет, и команда «останови» не
# имеет права его стирать.
#
# Стереть данные можно, но только явно: --with-data, и только после того,
# как человек своими руками наберёт слово подтверждения.
#
# ПРАВИШЬ ЗДЕСЬ — ПОПРАВЬ И В scripts/stack/down.ps1 (и наоборот); почему
# реализации две и что сторожит их совпадение — см. common.sh.

set -eu

SCRIPT_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
. "$SCRIPT_DIR/common.sh"

# --- Разбор аргументов -----------------------------------------------------

WITH_DATA=0
ASSUME_YES=0
for arg in "$@"; do
    case "$arg" in
        --with-data) WITH_DATA=1 ;;
        --yes|-y)    ASSUME_YES=1 ;;
        -h|--help)
            printf 'Использование: %s [--with-data [--yes]]\n\n' "$0"
            printf '  Без ключей: останавливает и удаляет контейнеры и сеть.\n'
            printf '  Данные (прогресс) сохраняются в томе %s.\n\n' "$DATA_VOLUME"
            printf '  --with-data  дополнительно удалить том %s.\n' "$DATA_VOLUME"
            printf '               ВЕСЬ ПРОГРЕСС БУДЕТ ПОТЕРЯН, восстановить его неоткуда.\n'
            printf '               Спрашивает подтверждение.\n'
            printf '  --yes        не спрашивать подтверждение (для скриптов).\n\n'
            printf 'Соседние команды: %s (запуск), %s (пересобрать с нуля).\n' \
                "$START_COMMAND" "$REBUILD_COMMAND"
            exit 0
            ;;
        *)
            printf 'Неизвестный аргумент: %s (см. --help)\n' "$arg" >&2
            exit 2
            ;;
    esac
done

# Откуда читать подтверждение. Выясняется ДО первого действия: отказ на
# полпути (контейнеры уже сняты, данные — нет) хуже отказа сразу.
#
# Терминал предпочтительнее stdin: команду могли запустить в пайпе, и тогда
# «ответом» стал бы случайный текст, а не решение человека. Проверяем
# открытием в подоболочке — /dev/tty существует всегда, но к процессу без
# управляющего терминала не подключается, и обычный read по нему падает
# системной ошибкой.
CONFIRM_SOURCE=''
if [ "$WITH_DATA" = "1" ] && [ "$ASSUME_YES" = "0" ]; then
    if (exec 3</dev/tty) 2>/dev/null; then
        CONFIRM_SOURCE='tty'
    elif [ -t 0 ]; then
        CONFIRM_SOURCE='stdin'
    else
        stop_with_problem 'некому подтвердить удаление данных' <<'HINTS'
Команда запущена без терминала, а удаление данных требует подтверждения.
Если это скрипт и удаление действительно нужно — добавь ключ --yes.
Ничего не тронуто: платформа в том же состоянии, что и до команды.
HINTS
    fi
fi

# Подтверждение набирается целым словом, а не «y/n»: на «y» палец попадает
# случайно, на «УДАЛИТЬ» — нет. Латинское DELETE принимается наравне с
# русским словом: в консоли без русской раскладки набрать его иначе нельзя.
confirm_data_removal() {
    if [ "$ASSUME_YES" = "1" ]; then
        write_note 'Подтверждение пропущено ключом --yes.'
        return 0
    fi
    printf '\n'
    printf '      %sБудет удалён том %s — это весь прогресс всех курсов на этом компьютере.%s\n' \
        "$C_YELLOW" "$DATA_VOLUME" "$C_OFF"
    printf '      %sВосстановить его будет неоткуда.%s\n\n' "$C_YELLOW" "$C_OFF"
    printf '      Чтобы подтвердить, набери УДАЛИТЬ (или DELETE) и нажми Enter: '
    if [ "$CONFIRM_SOURCE" = "tty" ]; then
        IFS= read -r _answer < /dev/tty || _answer=''
    else
        IFS= read -r _answer || _answer=''
    fi
    printf '\n'
    if [ "$_answer" != "УДАЛИТЬ" ] && [ "$_answer" != "DELETE" ]; then
        write_ok 'Данные не тронуты — удаление отменено.'
        printf '\n'
        exit 0
    fi
}

# --- Сценарий --------------------------------------------------------------

if [ "$WITH_DATA" = "1" ]; then
    TOTAL_STEPS=3
else
    TOTAL_STEPS=2
fi

write_banner 'остановка платформы'
stack_init

write_step 1 'Проверяю Docker'
ensure_docker_installed
# Незапущенный Docker останавливать нечего: контейнеры вместе с ним уже не
# работают. Поднимать его ради `down` — минуты ожидания ради ничего.
if ! test_docker_daemon; then
    write_ok 'Docker не запущен — значит, и контейнеры Trellis не работают.'
    printf '\n'
    write_detail 'Останавливать нечего. Данные платформы на месте.'
    printf '\n'
    exit 0
fi
write_ok 'Docker запущен.'

write_step 2 'Останавливаю и удаляю контейнеры'
printf '\n'
compose_down
printf '\n'
write_ok 'Контейнеры и сеть удалены.'

if [ "$WITH_DATA" = "1" ]; then
    write_step 3 'Удаляю данные платформы'
    confirm_data_removal
    remove_data_volume
    printf '\n'
    printf '  %sПлатформа остановлена, данные удалены.%s\n\n' "$C_GREEN" "$C_OFF"
    printf '      Следующий запуск (%s) создаст базу заново, с нуля.\n\n' "$START_COMMAND"
else
    printf '\n'
    printf '  %sПлатформа остановлена.%s\n\n' "$C_GREEN" "$C_OFF"
    printf '      Данные сохранены в томе %s — прогресс никуда не делся.\n\n' "$DATA_VOLUME"
    printf '      Запустить снова:         %s\n' "$START_COMMAND"
    printf '      После обновления файлов: %s (пересборка с нуля)\n\n' "$REBUILD_COMMAND"
fi

exit 0
