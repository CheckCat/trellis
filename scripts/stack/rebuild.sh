#!/bin/sh
# Пересборка локальной платформы Trellis с нуля (macOS / Linux).
#
# Для чего эта команда существует отдельно от start.sh. Обычный запуск
# собирает образы с кешем слоёв: это быстро и в большинстве случаев верно.
# Но после `git pull` кеш иногда оказывается умнее, чем надо, — слой с
# `npm ci` переиспользуется, потому что Docker не видит причины его
# пересобирать, и пользователь получает старые зависимости при новом коде.
# Разбираться, когда именно так вышло, обычному человеку не по силам;
# «пересобери всё начисто» — команда, которая чинит это без разбирательств.
#
# Данные НЕ трогаются: том trellis_pgdata переживает пересборку, миграции
# ядра накатятся на существующую базу, прогресс остаётся. Удаление данных —
# отдельная команда с подтверждением (down.sh --with-data).
#
# ПРАВИШЬ ЗДЕСЬ — ПОПРАВЬ И В scripts/stack/rebuild.ps1 (и наоборот); почему
# реализации две и что сторожит их совпадение — см. common.sh.

set -eu

SCRIPT_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
. "$SCRIPT_DIR/common.sh"

# --- Разбор аргументов -----------------------------------------------------

for arg in "$@"; do
    case "$arg" in
        --sync-passwords) SYNC_PASSWORDS=1 ;;
        -h|--help)
            printf 'Использование: %s [--sync-passwords]\n\n' "$0"
            printf '  Пересобирает образы начисто (без кеша) по текущему состоянию проекта\n'
            printf '  и поднимает платформу заново. Данные (прогресс) сохраняются.\n\n'
            printf '  --sync-passwords  привести пароли ролей Postgres к тем, что сейчас в .env.\n\n'
            printf 'Соседние команды: %s (обычный запуск), %s (остановить).\n' \
                "$START_COMMAND" "$DOWN_COMMAND"
            exit 0
            ;;
        *)
            printf 'Неизвестный аргумент: %s (см. --help)\n' "$arg" >&2
            exit 2
            ;;
    esac
done

# --- Сценарий --------------------------------------------------------------

TOTAL_STEPS=7

write_banner 'пересборка платформы с нуля'
stack_init

write_step 1 'Проверяю Docker'
ensure_docker_installed
ensure_docker_running

write_step 2 'Проверяю настройки (файл .env)'
ensure_env

write_step 3 'Останавливаю текущие контейнеры'
write_detail "Данные не трогаю: том $DATA_VOLUME остаётся на месте, прогресс сохранится."
printf '\n'
# Остановить надо ДО сборки, а не после: иначе новые образы соберутся, а
# работать будет всё ещё старый контейнер до самого `up`, и пользователь
# минуты сборки смотрел бы на живую старую версию, думая, что она новая.
compose_down
printf '\n'
write_ok 'Старые контейнеры остановлены и удалены.'

write_step 4 'Собираю образы заново, без кеша'
write_detail 'Это дольше обычного запуска: все слои собираются с нуля, обычно несколько минут.'
write_detail 'Ниже — вывод Docker, его можно не читать.'
printf '\n'
remember_volume_state
compose_build_no_cache

write_step 5 'Запускаю платформу'
printf '\n'
# `nobuild`: образы только что собраны начисто шагом выше, повторная сборка
# ничего бы не изменила и стоила бы ещё одного прохода по слоям.
compose_up_with_recovery nobuild

write_step 6 'Жду, пока платформа будет готова'
wait_for_stack

write_step 7 'Готово'
print_ready

exit 0
